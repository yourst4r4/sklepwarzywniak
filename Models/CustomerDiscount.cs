using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.EntityFrameworkCore;

namespace Warzywniak.Models;

[Table("customer_discounts")]
public partial class CustomerDiscount
{
    [Key]
    [Column("id")]
    public long Id { get; set; }

    [Column("user_id")]
    public long UserId { get; set; }

    [Column("discount_percent")]
    [Precision(5, 2)]
    public decimal DiscountPercent { get; set; }

    [Column("start_date", TypeName = "timestamp without time zone")]
    public DateTime? StartDate { get; set; }

    [Column("end_date", TypeName = "timestamp without time zone")]
    public DateTime? EndDate { get; set; }

    [ForeignKey("UserId")]
    [InverseProperty("CustomerDiscounts")]
    public virtual User User { get; set; } = null!;
}
